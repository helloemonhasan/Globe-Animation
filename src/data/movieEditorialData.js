function toRoman(num) {
  if (isNaN(num) || num <= 0) return "MMXXIV";
  const lookup = [
    ["M", 1000],
    ["CM", 900],
    ["D", 500],
    ["CD", 400],
    ["C", 100],
    ["XC", 90],
    ["L", 50],
    ["XL", 40],
    ["X", 10],
    ["IX", 9],
    ["V", 5],
    ["IV", 4],
    ["I", 1]
  ];
  let res = "";
  for (const [letter, val] of lookup) {
    while (num >= val) {
      res += letter;
      num -= val;
    }
  }
  return res || "I";
}
